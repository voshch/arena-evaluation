"""Writing base scenario directories and pruning generated ones; only files carrying `GENERATED_MARKER` are ever replaced."""

from __future__ import annotations

import os
import shutil
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from ..formats import write_scenario
from .populate import bt_type_source

GENERATED_MARKER = "# Generated - do not hand-edit; regenerate instead."


def is_generated(path: Path) -> bool:
    try:
        return GENERATED_MARKER in path.read_text()[:1200]
    except OSError:
        return False


class WouldOverwrite(Exception):
    pass


def write_base(
    doc: dict[str, Any],
    *,
    world_root: str | os.PathLike[str],
    profile: str,
    generator: str = "populate",
    force: bool = False,
    note: str = "",
) -> Path:
    """Write `scenarios/<profile>/scenario.yaml`; refuses to replace a hand-authored scenario unless `force`."""
    out = Path(world_root) / "scenarios" / profile
    existing = out / "scenario.yaml"
    if existing.is_file() and not force and not is_generated(existing):
        raise WouldOverwrite(f"{existing} already exists and was not generated by this tool. Pass force=True to replace it, or generate under a different name.")
    out.mkdir(parents=True, exist_ok=True)

    # `resolve_agent_type_path` resolves `./name.yaml` against the scenario's own directory
    if any(str((a.get("agent") or {}).get("agent_type", "")).startswith("./") for a in (doc.get("dynamic") or []) if isinstance(a, dict)):
        src = bt_type_source()
        if src.is_file():
            shutil.copy2(src, out / src.name)
    n = len(doc.get("dynamic") or [])
    header = "\n".join(
        (
            f"# Base scenario: {profile} ({n} pedestrian{'s' if n != 1 else ''})",
            f"# generator: {generator}",
            *([f"# {note}"] if note else []),
            "#",
            GENERATED_MARKER,
            "",
            "",
        )
    )
    write_scenario(out, doc, header)
    return out


def prune_generated(world_root: str | os.PathLike[str], keep: Sequence[str]) -> list[str]:
    root = Path(world_root) / "scenarios"
    wanted = set(keep)
    gone: list[str] = []
    for path in sorted(root.glob("*/scenario.yaml")):
        name = path.parent.name
        if name in wanted or not is_generated(path):
            continue
        shutil.rmtree(path.parent)
        gone.append(name)
    return gone
